/**
 * The only module in `src/` that knows D1 exists.
 *
 * Pages call the functions here and get plain objects back. That boundary is not decoration: on
 * the free tier a Worker invocation may issue 50 subrequests, and a page that queries in a loop
 * over its stations blows through that on a city like Sofia (283 devices). Everything below
 * aggregates in SQL and returns in a fixed, small number of queries — a city page is three, a
 * station page is three, regardless of how many sensors are involved.
 *
 * Absent is not zero. A column the ETL could not fill is NULL here and stays `null` all the way to
 * the renderer, which draws nothing rather than drawing a measurement of zero.
 */

import { env } from "cloudflare:workers";
import { paths, slug, type SignalKey } from "./site";

/** `Env` is generated by `wrangler types` from wrangler.jsonc — rerun it when a binding changes. */
const DB = () => env.DB;

