/**
 * Every country, densest first.
 *
 * 156 rows with their totals already rolled up — the reason the countries table exists. Computing
 * these with a GROUP BY over ten thousand cities on every request would work at this size and be
 * the same mistake as querying in a loop, just better hidden.
 */
/**
 * The same idea as `CITY_SORTS`, for countries.
 *
 * `NULLS LAST` is spelled out on every order that can meet one. A country with no sensor has no
 * comfort and no median, and SQLite sorts NULL first — so "cleanest air" opened with a screen of
 * countries that have no reading at all, which is the opposite of what the heading promises.
 */
export const COUNTRY_SORTS = {
  sensors: { sql: "station_count DESC, city_count DESC, name", label: "Most sensors" },
  best: { sql: "comfort DESC NULLS LAST, station_count DESC", label: "Most comfortable" },
  worst: { sql: "comfort ASC NULLS LAST, station_count DESC", label: "Least comfortable" },
  cleanest: { sql: "pm25_median ASC NULLS LAST, comfort DESC", label: "Cleanest air" },
  dirtiest: { sql: "pm25_median DESC NULLS LAST, comfort ASC", label: "Dirtiest air" },
  cities: { sql: "city_count DESC, name", label: "Most cities" },
  name: { sql: "name", label: "A–Z" },
} as const;

export type CountrySort = keyof typeof COUNTRY_SORTS;

export function countrySort(value: string | null | undefined): CountrySort {
  return value && value in COUNTRY_SORTS ? (value as CountrySort) : "sensors";
}

export async function listCountries(sort: CountrySort = "sensors"): Promise<CountryRow[]> {
  const { results } = await DB()
    .prepare(`SELECT * FROM countries ORDER BY ${COUNTRY_SORTS[sort].sql}`)
    .all<CountryRow>();
  return results ?? [];
}

/**
 * A country's cities. Sensor cities first, then by comfort, then by size.
 *
 * The last term used to be a position with no number behind it; since the GeoNames merge `rank` is
 * ordered by real population, so the tail of a long list is the largest towns rather than whatever
 * the source happened to emit first. That is what makes truncating at a few hundred honest.
 */
export async function getCitiesInCountry(countryId: number, limit = 200): Promise<CityRow[]> {
  const { results } = await DB()
    .prepare(
      `SELECT c.*, co.slug AS country_slug, co.name AS country
         FROM cities c JOIN countries co ON co.id = c.country_id
        WHERE c.country_id = ?1
        ORDER BY (c.station_count = 0), (c.comfort IS NULL), c.comfort DESC, c.rank
        LIMIT ?2`,
    )
    .bind(countryId, limit)
    .all<CityRow>();
  return results ?? [];
}

// ── cities ──────────────────────────────────────────────────────────────────

/**
 * Every city query selects through this.
 *
 * `country` and `country_slug` are joined in rather than stored on the row, which is the whole
 * point of the countries table: there is one spelling of "Turkey" in the database and one place
 * that owns it. The join is an indexed integer key and adds no query — the city page still costs
 * the same four round trips it always did.
 */
const CITY_SELECT = `
  SELECT c.*, co.slug AS country_slug, co.name AS country
    FROM cities c JOIN countries co ON co.id = c.country_id`;

/**
 * What makes a city rankable. Written once because the count printed beside a list has to agree
 * with the list — "showing the first 150 of 1 312" is a lie the moment these two drift apart.
 */
const RANKABLE = "c.comfort IS NOT NULL AND c.station_count > 0";

/**
 * How many devices before a city's number is a measurement rather than a sample.
 *
 * Three is a judgement, and here is the arithmetic behind it: 420 of the 904 scored cities have
 * exactly one device, and 587 have fewer than three. A single fifty-euro sensor on one balcony is
 * a reading about that balcony — it can sit beside a road, above a chimney, or in the sun, and
 * nothing in the data says which. With three there is a median, and a median of three survives one
 * of them being wrong.
 *
 * They keep their pages. They are only kept out of a *league table*, which is the one place a
 * number gets read as a comparison.
 */
export const RANK_MIN_SENSORS = 3;

export async function getCity(countrySlug: string, citySlug: string): Promise<CityRow | null> {
  return await DB()
    .prepare(`${CITY_SELECT} WHERE co.slug = ?1 AND c.slug = ?2`)
    .bind(slug(countrySlug), slug(citySlug))
    .first<CityRow>();
}

export async function getCityById(id: number): Promise<CityRow | null> {
  return await DB().prepare(`${CITY_SELECT} WHERE c.id = ?1`).bind(id).first<CityRow>();
}

