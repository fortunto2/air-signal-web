/**
 * Cities near a point, for the "nearby" rail. Bounded by a lat/lon box first so SQLite can use
 * the geo index; the exact distance ordering happens on the handful of rows that survive.
 */
export async function getNearbyCities(
  lat: number,
  lon: number,
  degrees = 2,
  limit = 6,
  excludeId?: number,
): Promise<CityRow[]> {
  const { results } = await DB()
    .prepare(
      `${CITY_SELECT}
        WHERE c.lat BETWEEN ?1 - ?3 AND ?1 + ?3
          AND c.lon BETWEEN ?2 - ?3 AND ?2 + ?3
          AND c.id != ?5
        ORDER BY (c.lat - ?1) * (c.lat - ?1) + (c.lon - ?2) * (c.lon - ?2)
        LIMIT ?4`,
    )
    .bind(lat, lon, degrees, limit, excludeId ?? -1)
    .all<CityRow>();
  return results ?? [];
}

/**
 * Search, by city name or by device id.
 *
 * Two questions arrive through one box because a reader does not know which they are asking. "sofia"
 * is a place; "82613" is a number printed on a box in someone's garden, and the person typing it is
 * usually its owner. Answering both from one field costs one extra query and saves explaining the
 * difference.
 *
 * Ordering is by size, not alphabetical: ten thousand cities contain a great many hamlets called
 * Springfield, and the one the reader meant is almost always the big one. `rank` is the position in
 * the source's population-ordered list, so it ascends — 0 is the largest city in its country. Places
 * with sensors are lifted above places without, because those are the pages with something to show.
 *
 * `LIKE 'q%'` uses the name index; `LIKE '%q%'` cannot, and on this table that is a full scan on
 * every keystroke. So a prefix match is the first pass and the contains-match is the fallback,
 * merged here rather than in SQL so the prefix hits always sort first.
 */
export interface SearchHit {
  kind: "city" | "station";
  id: number;
  name: string;
  detail: string;
  path: string;
  pm25: number | null;
  comfort: number | null;
}

export async function search(query: string, limit = 8): Promise<SearchHit[]> {
  const q = query.trim();
  if (q.length < 2) return [];

  const hits: SearchHit[] = [];

  // A bare number is a device id, and the reader wants that device — not the town whose name
  // happens to contain digits. Looked up first so it lands at the top.
  if (/^\d{2,7}$/.test(q)) {
    const station = await DB()
      .prepare(
        `SELECT s.id, s.pm25, s.sensor_type, c.name AS city_name, c.slug AS city_slug,
                co.slug AS country_slug
           FROM stations s
           LEFT JOIN cities c ON c.id = s.city_id
           LEFT JOIN countries co ON co.id = c.country_id
          WHERE s.id = ?1`,
      )
      .bind(Number(q))
      .first<{
        id: number;
        pm25: number | null;
        sensor_type: string | null;
        city_name: string | null;
        city_slug: string | null;
        country_slug: string | null;
      }>();

    if (station?.country_slug && station.city_slug) {
      hits.push({
        kind: "station",
        id: station.id,
        name: `Station ${station.id}`,
        detail: [station.city_name, station.sensor_type?.toUpperCase()].filter(Boolean).join(" · "),
        path: paths.station(station.country_slug, station.city_slug, station.id),
        pm25: station.pm25,
        comfort: null,
      });
    }
  }

  const like = q.replace(/[%_]/g, "");
  const { results } = await DB()
    .prepare(
      `${CITY_SELECT}
        WHERE c.name LIKE ?1 OR c.name LIKE ?2
        ORDER BY (c.name LIKE ?1) DESC,
                 (c.station_count > 0) DESC,
                 c.rank ASC
        LIMIT ?3`,
    )
    .bind(`${like}%`, `%${like}%`, limit)
    .all<CityRow>();

  for (const c of results ?? []) {
    hits.push({
      kind: "city",
      id: c.id,
      name: c.name,
      detail:
        c.country +
        (c.station_count > 0
          ? ` · ${c.station_count} sensor${c.station_count === 1 ? "" : "s"}`
          : " · modelled"),
      path: paths.city(c.country_slug, c.slug),
      pm25: c.pm25_median,
      comfort: c.comfort,
    });
  }

  return hits.slice(0, limit);
}

/**
 * Every city with a device, best comfort first — the ranking page.
 *
 * Deliberately not `getCityAggregates`: that one feeds the map and must stay lean, and adding the
 * signal blob to it would put ten thousand copies of a JSON string into a GeoJSON response for the
 * sake of a list nobody is looking at from the map.
 */
/**
 * How a list can be ordered.
 *
 * A ranking that only shows the best is half a ranking. Someone comparing three towns before
 * deciding where to spend a winter wants the bottom as much as the top, and someone who lives in
 * the bottom one wants to find it. The orders live here rather than in the page because the country
 * list needs the same set, and because a sort key arriving from a query string must never reach
 * SQL — this map is the allow-list that makes that impossible.
 */
export const CITY_SORTS = {
  best: { sql: "c.comfort DESC, c.station_count DESC", label: "Most comfortable" },
  worst: { sql: "c.comfort ASC, c.station_count DESC", label: "Least comfortable" },
  cleanest: { sql: "c.pm25_median ASC, c.comfort DESC", label: "Cleanest air" },
  dirtiest: { sql: "c.pm25_median DESC, c.comfort ASC", label: "Dirtiest air" },
  sensors: { sql: "c.station_count DESC, c.comfort DESC", label: "Most sensors" },
} as const;

export type CitySort = keyof typeof CITY_SORTS;

/** Whatever arrived, narrowed to something safe — an unknown key is the default, never an error. */
export function citySort(value: string | null | undefined): CitySort {
  return value && value in CITY_SORTS ? (value as CitySort) : "best";
}

export async function getRankedCities(
  limit = 200,
  sort: CitySort = "best",
  minSensors = RANK_MIN_SENSORS,
): Promise<CityRow[]> {
  // `pm25_median` can be NULL on a city whose devices all went quiet, and NULLs sort first in
  // SQLite — which would open "cleanest air" with a list of cities that have no reading at all.
  const nullsLast = sort === "cleanest" ? " AND c.pm25_median IS NOT NULL" : "";
  const { results } = await DB()
    .prepare(
      `${CITY_SELECT} WHERE ${RANKABLE}${nullsLast} AND c.station_count >= ?2
        ORDER BY ${CITY_SORTS[sort].sql} LIMIT ?1`,
    )
    .bind(limit, minSensors)
    .all<CityRow>();
  return results ?? [];
}

/** How many cities clear the bar, and how many are being held back by it. */
export async function countRankable(): Promise<{ eligible: number; thin: number }> {
  const row = await DB()
    .prepare(
      `SELECT SUM(c.station_count >= ?1) AS eligible, SUM(c.station_count < ?1) AS thin
         FROM cities c WHERE ${RANKABLE}`,
    )
    .bind(RANK_MIN_SENSORS)
    .first<{ eligible: number; thin: number }>();
  return { eligible: row?.eligible ?? 0, thin: row?.thin ?? 0 };
}

/** How many cities have a device at all — the total behind a truncated ranking. */
export async function countCitiesWithSensors(): Promise<number> {
  const row = await DB()
    .prepare(`SELECT COUNT(*) AS n FROM cities c WHERE ${RANKABLE}`)
    .first<{ n: number }>();
  return row?.n ?? 0;
}

/** Best and worst comfort today, for the home page. One query, not two passes. */
export async function getComfortExtremes(limit = 6): Promise<{ best: CityRow[]; worst: CityRow[] }> {
  const [best, worst] = await DB().batch<CityRow>([
    DB()
      .prepare(
        `${CITY_SELECT} WHERE ${RANKABLE} ORDER BY c.comfort DESC LIMIT ?1`,
      )
      .bind(limit),
    DB()
      .prepare(
        `${CITY_SELECT} WHERE ${RANKABLE} ORDER BY c.comfort ASC LIMIT ?1`,
      )
      .bind(limit),
  ]);
  return { best: best.results ?? [], worst: worst.results ?? [] };
}

/**
 * Store what a page just computed, so the next visitor does not compute it again.
 *
 * This is the one place the Worker writes, and the boundary is deliberate: it may fill the *cache*
 * columns of a row that already exists — the readings, the scores, the timestamp — and nothing
 * else. Cities and stations are created only by the ETL, so a bad request cannot invent a page or
 * change what the site is about. `ARCHITECTURE.md` states the rule; this function is its whole
 * surface.
 *
 * Called from `ctx.waitUntil`, so it never delays the response that produced the data.
 */
export async function saveCityReadings(
  cityId: number,
  data: {
    comfort: number;
    worstSignal: string | null;
    signals: Record<string, number>;
    readings: Record<string, number>;
  },
): Promise<void> {
  await DB()
    .prepare(
      `UPDATE cities
          SET comfort = ?2, worst_signal = ?3, signals_json = ?4, readings_json = ?5,
              updated_at = ?6
        WHERE id = ?1`,
    )
    .bind(
      cityId,
      data.comfort,
      data.worstSignal,
      JSON.stringify(data.signals),
      JSON.stringify(data.readings),
      new Date().toISOString(),
    )
    .run();
}

